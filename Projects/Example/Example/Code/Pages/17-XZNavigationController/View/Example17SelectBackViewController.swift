import UIKit

class Example17SelectBackViewController: UITableViewController {
    
    var selectedViewController: UIViewController? = nil
    
    private var viewControllers = [UIViewController]()

    override func viewDidLoad() {
        super.viewDidLoad()

        if let viewControllers = navigationController?.viewControllers {
            self.viewControllers.append(contentsOf: viewControllers)
        }
    }

    // MARK: - Table view data source

    override func numberOfSections(in tableView: UITableView) -> Int {
        return 1
    }

    override func tableView(_ tableView: UITableView, numberOfRowsInSection section: Int) -> Int {
        return viewControllers.count - 2
    }

    override func tableView(_ tableView: UITableView, cellForRowAt indexPath: IndexPath) -> UITableViewCell {
        let cell = tableView.dequeueReusableCell(withIdentifier: "cell", for: indexPath)

        let viewController = viewControllers[indexPath.row]
        cell.textLabel?.text = viewController.navigationItem.title
        
        if viewController == selectedViewController {
            cell.accessoryType = .checkmark
        } else {
            cell.accessoryType = .disclosureIndicator
        }

        return cell
    }
    
    override func tableView(_ tableView: UITableView, didSelectRowAt indexPath: IndexPath) {
        selectedViewController = viewControllers[indexPath.row]
        performSegue(withIdentifier: "confirm", sender: nil)
    }

